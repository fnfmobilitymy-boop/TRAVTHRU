import {test, expect} from '@playwright/test';
test('desktop: continuous scroll, fleet selection and trip consultation',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page).toHaveTitle(/TRAVTHRU/);
 await expect(page.locator('.hero h1')).toContainText('都值得');
 await page.evaluate(()=>scrollTo(0,document.querySelector('.journey-sequence').offsetTop+innerHeight*1.1));
 await expect.poll(()=>page.locator('#scene-count').textContent()).toBe('02 / 03');
 await expect(page.locator('.journey-landscape')).toHaveCSS('opacity','1');
 await page.getByRole('tab',{name:'5 座轿车'}).click();
 await expect(page.locator('#fleet-name')).toHaveText('Perodua Myvi');
 await page.locator('#fleet-next').click();
 await expect(page.locator('#fleet-name')).toHaveText('Hyundai Staria');
 await page.getByRole('tab',{name:'7 座 MPV'}).click();
 await page.locator('[data-variant="innova"]').click();
 await expect(page.locator('#fleet-name')).toHaveText('Toyota Innova');
 await page.locator('#fleet-book').click();
 await expect(page.locator('[name="vehicle"]')).toHaveValue('Toyota Innova');
 await page.locator('[name="name"]').fill('测试旅客');
 await page.locator('[name="email"]').fill('traveller@example.com');
 await page.locator('[name="date"]').fill('2027-01-20');
 await page.locator('[name="message"]').fill('KLIA 到吉隆坡酒店，2 人，2 件行李。');
 await page.locator('#booking-form button[type="submit"]').click();
 await expect(page.locator('#form-result')).toBeVisible();
 await expect(page.locator('#trip-summary')).toContainText('Toyota Innova');
 const href=await page.locator('#whatsapp-trip').getAttribute('href');
 expect(href).toMatch(/^https:\/\/wa.me\/60107198186\?text=/);
 expect(decodeURIComponent(href)).toContain('KLIA 到吉隆坡酒店');
 await page.getByText('可以安排机场接送和多日包车吗？').click();
 await expect(page.locator('details[open]')).toContainText('航班时间');
 await page.locator('#privacy-button').click();
 await expect(page.locator('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 expect(errors).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('mobile: navigation, fleet swipe, booking and reduced motion',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/');
 await page.getByRole('button',{name:'打开导航'}).click();
 await expect(page.locator('.nav nav')).toBeVisible();
 await page.locator('.nav nav a[href="#fleet"]').click();
 await expect(page.locator('.nav nav')).not.toBeVisible();
 await page.getByRole('tab',{name:'旅游巴士'}).click();
 await expect(page.locator('#fleet-name')).toHaveText('Touring Coach');
 await page.locator('#fleet-car').scrollIntoViewIfNeeded();
 const b=await page.locator('#fleet-car').boundingBox();
 await page.mouse.move(b.x+b.width*.7,b.y+b.height*.5);await page.mouse.down();
 await page.mouse.move(b.x+b.width*.25,b.y+b.height*.5,{steps:5});await page.mouse.up();
 await expect(page.locator('#fleet-name')).toHaveText('Perodua Myvi');
 await page.locator('#quick-service').selectOption('定制旅游');await page.locator('#quick-location').selectOption('槟城 · Penang');
 await page.locator('#quick-submit').click();
 await expect(page.locator('[name="service"]')).toHaveValue('定制旅游');
 await expect(page.locator('[name="message"]')).toHaveValue(/槟城/);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('English: translated content, persistent language, enquiry and live updates',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto('/?lang=en');
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await expect(page.locator('.hero h1')).toContainText('Every journey');
 await expect(page.locator('.nav nav')).toContainText('Our Services');
 await expect(page.locator('[name="name"]')).toHaveAttribute('placeholder','How should we address you?');
 await page.getByRole('tab',{name:'10-seat van',exact:true}).click();
 await expect(page.locator('#fleet-seats')).toHaveText('10-seat vehicle');
 await page.locator('#fleet-book').click();
 await page.locator('[name="name"]').fill('Alex Tan');
 await page.locator('[name="email"]').fill('alex@example.com');
 await page.locator('[name="date"]').fill('2027-01-20');
 await page.locator('[name="message"]').fill('Airport pick-up for 6 guests and 4 bags.');
 await page.locator('#booking-form button[type="submit"]').click();
 await expect(page.locator('#trip-summary')).toContainText('Vehicle: 10-seat van');
 await page.locator('[name="passengers"]').fill('6');
 await expect(page.locator('#trip-summary')).toContainText('Travellers: 6');
 await page.locator('#language-toggle').click();
 await expect(page.locator('html')).toHaveAttribute('lang','zh-CN');
 await expect(page.locator('#trip-summary')).toContainText('同行人数：6');
 await expect(page.locator('[name="name"]')).toHaveValue('Alex Tan');
 await expect(page.locator('[name="vehicle"]')).toHaveValue('10 座 VAN');
 await page.locator('#language-toggle').click();await page.reload();
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await page.goto('/');await expect(page.locator('html')).toHaveAttribute('lang','en');
 const untranslated=await page.evaluate(()=>{const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);const out=[];while(walker.nextNode()){const n=walker.currentNode;if(n.parentElement.closest('script,style,#language-toggle,pre'))continue;if(/[\u4e00-\u9fff]/.test(n.textContent)&&n.parentElement.getClientRects().length)out.push(n.textContent.trim())}return out});
 expect(untranslated).toEqual([]);
});
